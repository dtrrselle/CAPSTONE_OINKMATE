import {
  View,
  Text,
  ScrollView,
  TouchableOpacity,
  TextInput,
  StyleSheet,
  Platform,
  Modal,
  Pressable,
  ActivityIndicator,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { useRouter } from 'expo-router';
import AsyncStorage from '@react-native-async-storage/async-storage';

type ScheduleType = 'feeding' | 'sanitation';
type StatusType = 'active' | 'inactive';

// Pig Pen shape as loaded from api/schedules/get_farmer_pig_pens.php
type PigPen = {
  pen_id: number;
  pen_name: string;
  pig_count: number;
  pig_age_at_registration: number | string;
  avg_weight: number | string;
  currentAge: number | string;
  growthStage: string;
  feedType: string;
  recommendedFeed: string;
  source: string;
};


